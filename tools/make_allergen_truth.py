DOUBTS = []


def doubt(name, item, level, why):
    DOUBTS.append({'name': name, 'item': item, 'level': level, 'why': why})


class Judge:
    def __init__(self, name):
        self.name = name
        self.a = {}

    def y(self, *items):
        for k in items:
            self.a[k] = 'yes'

    def m(self, *items):
        for k in items:
            if self.a.get(k) != 'yes':
                self.a[k] = 'maybe'

    def no(self, *items):
        for k in items:
            self.a.pop(k, None)

    def d(self, item, level, why):
        doubt(self.name, item, level, why)
        (self.y if level == 'yes' else self.m)(item)


