def judge_dish(d, food_truth):
    """料理の正解 = 材料の正解の和（食品番号で引く）＋ 料理に付けた印（yes）"""
    a = {}
    for it in d['items']:
        for k, v in food_truth.get(it['no'], {}).get('a', {}).items():
            if v == 'yes' or a.get(k) != 'yes':
                a[k] = v
    for k in d.get('allergy', []):
        if a.get(k) != 'yes':
            if k not in a:
                doubt(d['name'], k, 'yes', '料理に付けた印にあるが材料の名前からは出ない（パン粉・バターなどの印）')
            a[k] = 'yes'
    return a


