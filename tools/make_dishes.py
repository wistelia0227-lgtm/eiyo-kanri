def main():
    check_only = '--check' in sys.argv
    out, bad = [], []
    for d in D:
        items = []
        for q, g in d['items']:
            hits = find(q)
            if not hits:
                bad.append((d['name'], q))
                continue
            items.append({'no': hits[0][0], 'name': hits[0][3], 'g': g, 'q': q, 'alt': len(hits)})
        kcal = sum(val(find(i['q'])[0], 'kcal') * i['g'] / 100 for i in items)
        nacl = sum(val(find(i['q'])[0], 'nacl') * i['g'] / 100 for i in items)
        prot = sum(val(find(i['q'])[0], 'prot') * i['g'] / 100 for i in items)
        tg = TAGS.get(d['name'], ('', ''))
        out.append({'name': d['name'], 'kind': d['kind'], 'allergy': d['allergy'], 'memo': d['memo'],
                    'main': tg[0], 'method': tg[1],
                    'items': items, 'kcal': round(kcal), 'nacl': round(nacl, 2), 'prot': round(prot, 1)})

    print('料理 %d 件' % len(out))
    if bad:
        print('\n★ 食品が見つからない材料:')
        for n, q in bad:
            print('   %s / %s' % (n, q))
    print('\n引き当てた材料（候補が複数あるものは件数つき）:')
    seen = {}
    for d in out:
        for i in d['items']:
            if i['q'] in seen:
                continue
            seen[i['q']] = 1
            print('   %-38s → %s  %s%s' % (i['q'], i['no'], i['name'], ('  [候補%d]' % i['alt']) if i['alt'] > 1 else ''))
    print('\n栄養価（1 人分）:')
    for d in sorted(out, key=lambda x: -x['kcal']):
        print('   %-22s %4d kcal  たんぱく質 %5.1f g  食塩 %4.2f g' % (d['name'], d['kcal'], d['prot'], d['nacl']))

    if check_only or bad:
        if bad:
            print('\n見つからない材料があるので書き出しませんでした。')
        return
    notag = [d['name'] for d in out if not d['main']]
    if notag:
        print(chr(10) + '★ 主材料・調理法が付いていない料理: ' + '、'.join(notag))
        return
    names = set(d['name'] for d in out)
    missing = sorted({n for day in CYCLE for meal in day for n in meal if n not in names})
    if missing:
        print(chr(10) + '★ サイクル献立に、定義していない料理があります: ' + '、'.join(missing))
        return
    kinds = {d['name']: d['kind'] for d in out}
    kcalOf = {d['name']: d['kcal'] for d in out}
    naclOf = {d['name']: d['nacl'] for d in out}
    protOf = {d['name']: d['prot'] for d in out}
    print(chr(10) + 'サイクル献立 %d 日分の 1 日あたり:' % len(CYCLE))
    for i, day in enumerate(CYCLE):
        k = sum(kcalOf[n] for meal in day for n in meal)
        na = sum(naclOf[n] for meal in day for n in meal)
        pr = sum(protOf[n] for meal in day for n in meal)
        print('   %2d 日目  %4d kcal  たんぱく質 %5.1f g  食塩 %4.1f g' % (i + 1, k, pr, na))
    ks = [sum(kcalOf[n] for meal in day for n in meal) for day in CYCLE]
    ns = [sum(naclOf[n] for meal in day for n in meal) for day in CYCLE]
    print('   平均 %4d kcal（%d〜%d）  食塩 %.1f g' % (sum(ks) / len(ks), min(ks), max(ks), sum(ns) / len(ns)))
    void = [kinds]

