# ---- 成分表を読む ----
raw = open(DATA, encoding='utf-8').read()
raw = raw[raw.index('{'):].rstrip().rstrip(';')
DB = json.loads(raw)
FOODS = DB['foods']
NUTR = [n['key'] for n in DB['meta']['nutrients']]
HEAD = len(DB['meta']['head'])
KEY = {k: i for i, k in enumerate(NUTR)}


def norm(s):
    s = s.replace('　', ' ')
    s = re.sub(r'[\[\]（）()＜＞<>　]', ' ', s)
    return re.sub(r'\s+', ' ', s).strip()


BYNO = {r[0]: r for r in FOODS}


def find(query, prefer_group=None):
    """5 桁の食品番号ならその食品。そうでなければ、探す言葉を全部含む食品を名前が短い順に返す"""
    if re.fullmatch(r'\d{5}', query):
        r = BYNO.get(query)
        return [r] if r else []
    words = query.split()
    hits = []
    for r in FOODS:
        name = norm(r[3])
        if all(w in name for w in words):
            if prefer_group and r[1] != prefer_group:
                continue
            hits.append(r)
    hits.sort(key=lambda r: (len(r[3]), r[0]))
    return hits


def val(row, key):
    v = row[HEAD + KEY[key]]
    return 0 if v is None else v


